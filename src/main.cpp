// Frame-pace probe (PERMANENT harness instrumentation, same class as state_probe): counts game
// framebuffer swaps by watching ultramodern's native VI_ORIGIN register once per VI. AeroGauge's
// swap path is fully native, so the runtime register is the evidence source. At most one swap
// can become current per retrace, so per-VI sampling cannot miss one. About 0.5 swaps/VI is
// expected for a 30 fps title on a 60 Hz VI; about 1.0 means the game may be running twice as fast.
static void pace_probe(int vi_n) {
    static uint32_t s_last_origin = 0;
    const ultramodern::renderer::ViRegs* vr = ultramodern::renderer::get_vi_regs();
    if (vr == nullptr) return;
    uint32_t origin = vr->VI_ORIGIN_REG;
    if (origin != s_last_origin) {
        s_last_origin = origin;
        int s = ++g_swaps;
        // The periodic (s % 256, ~8.5 s) line is gated behind AERO_HARNESS_LOG: it runs
        // on the VI thread -- the game's master pacer -- and a synchronous console write
        // here stalls pacing itself (same hitch class as the gfx-thread heartbeat, see
        // rt64_renderer.cpp). The first-8-swaps boot lines are one-time and stay.
        if (s <= 8 || (aero::config::harness_log() && (s % 256) == 0))
            std::fprintf(stderr, "[probe] fb swap #%d -> VI_ORIGIN=0x%08x (vi=%d)\n",
                         s, origin, vi_n);
    }
}

// Provided by local runtime patch 0001. The legacy symbol and environment
// variable names are part of that patch's ABI; see docs/reference/runtime.md.
extern "C" void lambo_thread_trace_dump(int vi);
// Scripted warp trigger (PERMANENT harness instrumentation, same class as state_probe):
// AERO_WARP_AT=vi:track[:craft] (track/craft 1-based, like AERO_WARP) publishes a warp
// request at the given VI from this main-thread callback — the same cross-thread path the
// F1-F6 hotkeys use — so headless runs can exercise mid-run and mid-race re-warps.
static void warp_at_probe(int vi_n) {
    static int at = -1, track = 0, craft = 0;
    if (at == -1) {
        at = 0;
        if (const char* e = std::getenv("AERO_WARP_AT")) {
            if (std::sscanf(e, "%d:%d:%d", &at, &track, &craft) < 2 || track < 1 || track > 6) {
                std::fprintf(stderr, "[warp] AERO_WARP_AT=%s invalid: vi:track[:craft]\n", e);
                at = 0;
            }
        }
    }
    if (at > 0 && vi_n == at) aero_warp_request(track - 1, craft - 1);
}

// VI-thread pacing probe (PERMANENT harness instrumentation, companion to the gfx-thread
// probe in rt64_renderer.cpp; enabled by the same AERO_FRAME_LOG=<path>, writing to
// <path>.vi): vi_cb runs once per VI tick on ultramodern's VI thread, so a gap here means
// the PACER stalled (Sleep granularity / timer / message-queue / console-lock contention),
// as opposed to a gfx-thread stall. Lines are tagged [vi-pace] vs the gfx probe's [gfx-pace].
static void vi_pace_probe() {
    static FILE* f = aero::config::open_frame_log(".vi");
    if (f == nullptr) return;
    using clock = std::chrono::steady_clock;
    static const auto t0 = clock::now();
    static clock::time_point last{};
    const auto now = clock::now();
    if (last.time_since_epoch().count() != 0) {
        double gap = std::chrono::duration<double, std::milli>(now - last).count();
        if (gap > 25.0) {
            std::fprintf(f, "[vi-pace] t=%.1f VI tick gap=%.2fms\n",
                         std::chrono::duration<double, std::milli>(now - t0).count(), gap);
            std::fflush(f);
        }
    }
    last = now;
}

static void vi_cb() {
#if defined(__ANDROID__)
    aero::android::wait_foreground();
#endif
    vi_pace_probe();
    state_probe();
    menu_probe();
    int n = ++g_vis;
    warp_at_probe(n);
    pace_probe(n);
    if ((n % 50) == 0) lambo_thread_trace_dump(n); // Diagnostic snapshot of thread message activity.
    if (!g_first_vi.exchange(true)) std::fprintf(stderr, "[probe] FIRST VI retrace\n");
    if (n == kQuitAfterVis) {
        std::fprintf(stderr, "[probe] reached %d VIs; quitting\n", n);
        boot_summary_and_exit();
    }
}

