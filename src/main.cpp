// --- rumble-pak sink (#69) ----------------------------------------------------------------
// The game's SI/PIF bridge (func_8007F780 -> aero_joybus_answer, recomp/src/libultra_stubs.c)
// runs on the GAME thread and decodes the ROM's motor-control pak writes (joybus cmd 0x03 to
