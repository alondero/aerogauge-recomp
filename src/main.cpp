// Print the one-line boot summary the runtime guard (tests/pivot/test_boot_smoke.py) parses,
// then terminate the process immediately. We _Exit instead of returning through
// recomp::start()'s teardown on purpose: that teardown joins the helper threads and munmaps
// RDRAM, but it does NOT terminate the 7 game osCreateThread threads -- once the main game
// thread actually runs its per-frame dispatch loop, those threads are live in native
// osRecvMesg and race the munmap into a SIGSEGV. This is a headless boot/probe harness that is
// quitting anyway, so skip the unwind and let process exit tear the game threads down.
// (Graceful game-thread shutdown is RT64-integration work, #58.)
[[noreturn]] static void boot_summary_and_exit() {
    std::fprintf(stderr, "[probe] boot summary; threads=%d vis=%d first_vi=%d max_state=%d swaps=%d\n",
                 g_threads.load(), g_vis.load(), (int)g_first_vi.load(), g_max_state.load(),
                 g_swaps.load());
    std::fflush(nullptr);
    std::_Exit(g_first_vi.load() ? 0 : 2);
}


// The Lamborghini stack carried a retrace-time __osViSwapContext bridge here
// (promote_vi_context): that ROM's osScheduler read the PRIVATE VI-manager globals
// __osViCurr/__osViNext directly, so the port had to emulate the VI interrupt's
// pointer promotion or the gfx-task gate latched shut after one frame.
//
// AeroGauge does NOT need it (verified 2026-07-11 by an all-.text immediate scan for
// its VI globals __osViCurr=0x80094C50 / __osViNext=0x80094C54, scratchpad globref.py):
// every reference lives inside libultra itself — the routed osVi* API bodies, the
// collapsed __osViInit (0x80077120), and the VI-ISR-only __osViSwapContext
// (0x80077FD0/0x800782F0), which never runs recompiled. Game code goes exclusively
// through the public osVi* entry points, all routed to ultramodern natives, so the
// native VI manager owns the whole swap path and there is no private state to mirror.

// Scene-manager progression tracker (PERMANENT harness instrumentation, not a throwaway
// diagnostic). AeroGauge's top-level state is its scene manager (derived 2026-07-12 by a
// ROM jump-table scan + live probing, see src/aero_warp.c for the full map): the per-frame
// driver func_80015C8C copies the requested scene 0x8013FF84 into the current scene
// 0x8013FF80 and jump-tables to the scene runner; 0x8013FF88 is the scene-local phase
// (race: 1 load -> 2 intro -> 3 playing; 6 = fresh entry; 7 = exit sequence) and
// 0x8013FF90 the race-parameter block (mode byte: 4 = menu race, 7 = attract demo).
// Scenes: 0/1 boot logo, 2 attract, 3 title, 4 menu, 5 race. We log every transition of
// (scene, request, phase, race-mode) and record the highest scene reached (g_max_state)
// so a run reports "stuck vs progressing" instead of just "didn't crash".
static void state_probe() {
    uint8_t* rdram = g_aero_rdram;
    if (rdram == nullptr) return;
    auto w32 = [&](uint32_t a) -> uint32_t {
        return *(uint32_t*)(rdram + ((a & ~3u) - 0x80000000u));
    };
    auto b8 = [&](uint32_t a) -> uint32_t {
        return (w32(a & ~3u) >> (24 - 8 * (a & 3u))) & 0xFF;
    };
    uint32_t scene = w32(0x8013FF80), req = w32(0x8013FF84);
    uint32_t phase = w32(0x8013FF88), mode = b8(0x8013FF90);
    static uint32_t last[4] = { ~0u, ~0u, ~0u, ~0u };
    if (scene != last[0] || req != last[1] || phase != last[2] || mode != last[3]) {
        std::fprintf(stderr, "[state] vi=%d  scene=%u req=%u phase=%u race_mode=%u\n",
                     g_vis.load(), scene, req, phase, mode);
        last[0] = scene; last[1] = req; last[2] = phase; last[3] = mode;
    }
    if ((int)scene > g_max_state.load() && scene < 64) g_max_state.store((int)scene);
}

