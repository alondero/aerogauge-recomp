static ultramodern::renderer::WindowHandle create_window_stub(void* /*gfx_data*/) {
    // RT64 default presenter: RT64 needs a real window with a graphics surface
    // (Linux). Created on the main thread; the SDL event pump runs in update_gfx_stub
    // below (also main thread, via recomp::start's loop). AERO_HEADLESS=1 (harness
    // knob) skips the window entirely; SDL failure degrades to headless the same way.
    if (aero_rt64::enabled()) {
        // Enable SDL2's native Steam Controller HIDAPI driver (original Steam Controller); newer
        // pads (incl. Steam Controller Gen2 via Steam Input) present as a standard XInput gamepad
        // that the SDL_GameController API handles without this hint. Must precede SDL init.
        SDL_SetHint(SDL_HINT_JOYSTICK_HIDAPI_STEAM, "1");
        // Keep controller events flowing even when the window loses focus (matches the reference
        // ports; otherwise held inputs freeze on alt-tab).
        SDL_SetHint(SDL_HINT_JOYSTICK_ALLOW_BACKGROUND_EVENTS, "1");
        // GAMECONTROLLER pulls in JOYSTICK and enables controller hot-plug events.
        if (SDL_InitSubSystem(SDL_INIT_VIDEO | SDL_INIT_GAMECONTROLLER) != 0) {
            std::fprintf(stderr, "[rt64] SDL_InitSubSystem(VIDEO|GAMECONTROLLER) failed: %s -- staying headless\n",
                         SDL_GetError());
            return ultramodern::renderer::WindowHandle{};
        }
        SDL_SetEventFilter(sdl_event_filter, nullptr);
        // RecompFrontend opens controllers, enables sensors, and registers their
        // profiles while consuming ADDED events. SDL does not enqueue ADDED for
        // devices present before initialization, so replay those notifications
        // through the same owner instead of opening a second port-local handle.
        for (int i = 0; i < SDL_NumJoysticks(); i++) {
            if (!SDL_IsGameController(i)) continue;
            SDL_Event event{};
            event.type = SDL_CONTROLLERDEVICEADDED;
            event.cdevice.which = i;
            SDL_PushEvent(&event);
        }
        uint32_t flags = SDL_WINDOW_RESIZABLE;
#if defined(__ANDROID__)
        flags |= SDL_WINDOW_FULLSCREEN_DESKTOP;
#endif
#if defined(__linux__)
        flags |= SDL_WINDOW_VULKAN;
#endif
        // Window size + startup fullscreen come from graphics.json (loaded in main()
        // before recomp::start). Fullscreen is owned by SDL on this (main) thread --
        // see the F11 handler in update_gfx_stub.
        const aero::config::WindowSize win_size = aero::config::window_size();
        if (ultramodern::renderer::get_graphics_config().wm_option ==
            ultramodern::renderer::WindowMode::Fullscreen) {
            flags |= SDL_WINDOW_FULLSCREEN_DESKTOP;
        }
        SDL_Window* window = SDL_CreateWindow("AeroGauge",
                                              SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                                              win_size.width, win_size.height, flags);
        if (window == nullptr) {
            std::fprintf(stderr, "[rt64] SDL_CreateWindow failed: %s -- staying headless\n",
                         SDL_GetError());
            return ultramodern::renderer::WindowHandle{};
        }
        aero::menu::attach(window);
#if defined(__linux__)
        std::fprintf(stderr, "[rt64] SDL window created (%dx%d, Vulkan surface)\n",
                     win_size.width, win_size.height);
        return ultramodern::renderer::WindowHandle{window};
#elif defined(_WIN32)
        // Native Windows: ultramodern's WindowHandle is {HWND, thread_id} and
        // RT64 drives its D3D12 swapchain from the raw HWND. Unwrap it from
        // the SDL window on this thread.
        SDL_SysWMinfo wmInfo;
        SDL_VERSION(&wmInfo.version);
        if (SDL_GetWindowWMInfo(window, &wmInfo) != SDL_TRUE) {
            std::fprintf(stderr, "[rt64] SDL_GetWindowWMInfo failed: %s -- staying headless\n",
                         SDL_GetError());
            SDL_DestroyWindow(window);
            return ultramodern::renderer::WindowHandle{};
        }
        std::fprintf(stderr, "[rt64] SDL window created (%dx%d, Win32 HWND -> D3D12)\n",
                     win_size.width, win_size.height);
        return ultramodern::renderer::WindowHandle{wmInfo.info.win.window, GetCurrentThreadId()};
#else
        std::fprintf(stderr, "[rt64] window handle wiring not implemented on this platform\n");
        SDL_DestroyWindow(window);
        return ultramodern::renderer::WindowHandle{};
#endif
    }
    return ultramodern::renderer::WindowHandle{}; // headless: null handle
}

static void update_gfx_stub(void* /*gfx_data*/) {
    // Pump SDL events and sample frontend input on the main thread. The
    // frontend consumes the queue so binding scans and UI navigation see the
    // same events as gameplay.
    if (aero_rt64::enabled()) {
        aero::menu::update();
        recompinput::handle_events();
        refresh_menu_toggle_bindings();
#if defined(__ANDROID__)
        if (g_android_back_requested.exchange(false, std::memory_order_acq_rel)) {
            aero::android::controller_back();
        }
        const Uint32 lifecycle_event = g_android_lifecycle_event.exchange(0, std::memory_order_acq_rel);
        if (lifecycle_event != 0) {
            SDL_Event event{};
            event.type = lifecycle_event;
            aero::android::handle_event(event);
        }
#endif
        if (g_menu_toggle_requested.exchange(false, std::memory_order_acq_rel)) {
            aero::menu::toggle();
        }
        if (g_fullscreen_requested.exchange(false, std::memory_order_acq_rel)) {
            aero::menu::toggle_fullscreen();
        }
        if (g_window_close_requested.exchange(false, std::memory_order_acq_rel)) {
            std::fprintf(stderr, "[probe] window closed; quitting\n");
            release_all_controller_handles();
            aero::menu::update();
            boot_summary_and_exit();
        }
        recompinput::poll_inputs();
        sample_input();
        developer_input_tick();
        release_removed_controllers();
        refresh_rumble_controller();
        rumble_apply();
    }
}

