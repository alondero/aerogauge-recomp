// Scripted warp trigger (PERMANENT harness instrumentation, same class as state_probe):
// AERO_WARP_AT=vi:track[:craft] (track/craft 1-based, like AERO_WARP) publishes a warp
// request at the given VI from this main-thread callback — the same cross-thread path the
// F1-F6 hotkeys use — so headless runs can exercise mid-run and mid-race re-warps.
static void warp_at_probe(int vi_n) {
    static int at = -1, track = 0, craft = 0;
    if (at == -1) {
        at = 0;
        if (const char* e = std::getenv("AERO_WARP_AT")) {
            if (std::sscanf(e, "%d:%d:%d", &at, &track, &craft) < 2 || track < 1 || track > 6) {
                std::fprintf(stderr, "[warp] AERO_WARP_AT=%s invalid: vi:track[:craft]\n", e);
                at = 0;
            }
        }
    }
    if (at > 0 && vi_n == at) aero_warp_request(track - 1, craft - 1);
}

// VI-thread pacing probe (PERMANENT harness instrumentation, companion to the gfx-thread
// probe in rt64_renderer.cpp; enabled by the same AERO_FRAME_LOG=<path>, writing to
// <path>.vi): vi_cb runs once per VI tick on ultramodern's VI thread, so a gap here means
// the PACER stalled (Sleep granularity / timer / message-queue / console-lock contention),
// as opposed to a gfx-thread stall. Lines are tagged [vi-pace] vs the gfx probe's [gfx-pace].
static void vi_pace_probe() {
    static FILE* f = aero::config::open_frame_log(".vi");
    if (f == nullptr) return;
    using clock = std::chrono::steady_clock;
    static const auto t0 = clock::now();
    static clock::time_point last{};
    const auto now = clock::now();
    if (last.time_since_epoch().count() != 0) {
        double gap = std::chrono::duration<double, std::milli>(now - last).count();
        if (gap > 25.0) {
            std::fprintf(f, "[vi-pace] t=%.1f VI tick gap=%.2fms\n",
                         std::chrono::duration<double, std::milli>(now - t0).count(), gap);
            std::fflush(f);
        }
    }
    last = now;
}

static void vi_cb() {
    vi_pace_probe();
    state_probe();
    menu_probe();
    int n = ++g_vis;
    warp_at_probe(n);
    pace_probe(n);
    if ((n % 50) == 0) lambo_thread_trace_dump(n); // THROWAWAY: per-thread recv/send snapshot to find the frozen thread
    if (!g_first_vi.exchange(true)) std::fprintf(stderr, "[probe] FIRST VI retrace\n");
    if (n == kQuitAfterVis) {
        std::fprintf(stderr, "[probe] reached %d VIs; quitting\n", n);
        boot_summary_and_exit();
    }
}

