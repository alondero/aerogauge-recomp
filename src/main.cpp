// Events outside RecompFrontend's generic input contract remain port
// responsibilities. Filtering them before they enter the queue preserves the
// existing close/F10/Android behavior without a second SDL polling loop.
static bool is_fixed_keyboard_menu_toggle(const SDL_KeyboardEvent& event) {
    return event.keysym.sym == SDLK_ESCAPE || event.keysym.sym == SDLK_F10 ||
           event.keysym.sym == SDLK_AC_BACK;
}

static bool is_fixed_controller_menu_toggle(const SDL_ControllerButtonEvent& event) {
    return event.button == SDL_CONTROLLER_BUTTON_BACK;
}

static bool is_custom_controller_menu_toggle(const SDL_ControllerButtonEvent& event) {
    if (event.button < 0 || event.button >= 32) return false;
    std::lock_guard lock(g_menu_toggle_bindings_mutex);
    return (g_custom_controller_toggle_buttons &
            (uint32_t(1) << event.button)) != 0;
}

static bool is_custom_keyboard_menu_toggle(const SDL_KeyboardEvent& event) {
    const int scancode = event.keysym.scancode;
    if (scancode < 0 || scancode >= SDL_NUM_SCANCODES) return false;
    const uint64_t mask = uint64_t(1) << (scancode % 64);
    std::lock_guard lock(g_menu_toggle_bindings_mutex);
    return (g_custom_keyboard_toggle_scancodes[scancode / 64] & mask) != 0;
}

static int sdl_event_filter(void*, SDL_Event* event) {
#if defined(__ANDROID__)
    if (event->type == SDL_APP_WILLENTERBACKGROUND || event->type == SDL_APP_TERMINATING) {
        g_android_lifecycle_event.store(event->type, std::memory_order_release);
    }
#endif
    const bool binding = recompinput::binding::is_binding();
    if (event->type == SDL_CONTROLLERDEVICEREMOVED) {
        // The frontend opens controller handles while consuming ADDED events,
        // but does not close them when removing its state. Defer the close to
        // update_gfx_stub, where SDL calls are on the owning thread.
        std::lock_guard lock(g_removed_controller_mutex);
        if (SDL_GameController* controller =
                recompinput::get_controller_from_joystick_id(event->cdevice.which)) {
            if (std::find(g_removed_controllers.begin(), g_removed_controllers.end(), controller) ==
                g_removed_controllers.end()) {
                g_removed_controllers.push_back(controller);
            }
        }
    }
    if (event->type == SDL_QUIT ||
        (event->type == SDL_WINDOWEVENT && event->window.event == SDL_WINDOWEVENT_CLOSE)) {
        g_window_close_requested.store(true, std::memory_order_release);
        return 0;
    }
#if defined(__ANDROID__)
    if (!binding &&
        ((event->type == SDL_CONTROLLERBUTTONDOWN && event->cbutton.button == SDL_CONTROLLER_BUTTON_BACK) ||
         (event->type == SDL_KEYDOWN && !event->key.repeat && event->key.keysym.sym == SDLK_AC_BACK))) {
        g_android_back_requested.store(true, std::memory_order_release);
        return 0;
    }
#endif
    if (!binding &&
        ((event->type == SDL_KEYDOWN && is_fixed_keyboard_menu_toggle(event->key)) ||
         (event->type == SDL_KEYUP && is_fixed_keyboard_menu_toggle(event->key)) ||
         (event->type == SDL_CONTROLLERBUTTONDOWN && is_fixed_controller_menu_toggle(event->cbutton)) ||
         (event->type == SDL_CONTROLLERBUTTONUP && is_fixed_controller_menu_toggle(event->cbutton)))) {
        if ((event->type == SDL_KEYDOWN && !event->key.repeat) ||
            event->type == SDL_CONTROLLERBUTTONDOWN) {
            g_menu_toggle_requested.store(true, std::memory_order_release);
        }
        return 0;
    }
    if (!binding &&
        ((event->type == SDL_KEYDOWN && is_custom_keyboard_menu_toggle(event->key)) ||
         (event->type == SDL_KEYUP && is_custom_keyboard_menu_toggle(event->key)) ||
         (event->type == SDL_CONTROLLERBUTTONDOWN && is_custom_controller_menu_toggle(event->cbutton)) ||
         (event->type == SDL_CONTROLLERBUTTONUP && is_custom_controller_menu_toggle(event->cbutton)))) {
        if ((event->type == SDL_KEYDOWN && !event->key.repeat) ||
            event->type == SDL_CONTROLLERBUTTONDOWN) {
            g_menu_toggle_requested.store(true, std::memory_order_release);
        }
        // Configurable toggles are consumed here so RecompFrontend cannot
        // open the same menu a second time.
        return 0;
    }
    if (event->type == SDL_KEYDOWN && !event->key.repeat && event->key.keysym.sym == SDLK_F8 &&
        !aero::menu::captures_input()) {
        return 0;
    }
    if (event->type == SDL_KEYDOWN && !event->key.repeat &&
        (event->key.keysym.sym == SDLK_F11 ||
         (event->key.keysym.sym == SDLK_RETURN && (event->key.keysym.mod & KMOD_ALT)))) {
        g_fullscreen_requested.store(true, std::memory_order_release);
        return 0;
    }
    return 1;
}

// Runtime motor callbacks and race-event feedback share a thread-safe publisher.
// SDL calls stay on the main thread, which owns controller open/close.
extern "C" void aero_pak_set_rumble(int on) { aero::haptics::motor(on != 0); }
static void rumble_apply() {
    static bool was_on = false;
    if (g_pad == nullptr || !SDL_GameControllerGetAttached(g_pad)) {
        was_on = false;
        return;
    }
    const auto motors = aero::haptics::sample();
    const bool on = motors.low != 0 || motors.high != 0;
    if (on || was_on)
        SDL_GameControllerRumble(g_pad, motors.low, motors.high, on ? 150 : 0);
    was_on = on;
}

// Read the frontend mapping on the SDL thread and publish the same compact
// snapshot shape used by the headless harness. The runtime callback runs on a
// game thread and must not call SDL or inspect frontend controller state there.
static void sample_input() {
    uint16_t buttons = 0;
    float normalized_x = 0.0f;
    float normalized_y = 0.0f;
#if defined(__ANDROID__)
    int touch_x = 0, touch_y = 0;
    uint16_t touch_buttons = 0;
#endif

    if (!aero::menu::captures_input()) {
        recompinput::profiles::get_n64_input(0, &buttons, &normalized_x, &normalized_y);
#if defined(__ANDROID__)
        aero::android::sample_touch(touch_buttons, touch_x, touch_y);
#endif
    }

#if defined(__ANDROID__)
    const auto sampled = aero_sample_input(buttons, normalized_x, normalized_y,
                                           touch_buttons, touch_x, touch_y);
#else
    const auto sampled = aero_sample_input(buttons, normalized_x, normalized_y);
#endif
    g_input_snapshot.store(aero_input_pack(sampled.buttons, sampled.stick_x, sampled.stick_y),
                           std::memory_order_relaxed);
}

static void refresh_menu_toggle_bindings() {
    std::lock_guard lock(g_menu_toggle_bindings_mutex);
    std::array<uint64_t, kScancodeWords> keyboard{};
    uint32_t controller = 0;
    const int keyboard_profile = recompinput::profiles::get_sp_keyboard_profile_index();
    if (keyboard_profile >= 0) {
        for (size_t i = 0; i < recompinput::num_bindings_per_input; i++) {
            const auto field = recompinput::profiles::get_input_binding(
                keyboard_profile, recompinput::GameInput::TOGGLE_MENU, i);
            if (field.input_type == recompinput::InputType::Keyboard &&
                field.input_id != SDL_SCANCODE_ESCAPE &&
                field.input_id != SDL_SCANCODE_F10 &&
                field.input_id >= 0 && field.input_id < SDL_NUM_SCANCODES) {
                keyboard[field.input_id / 64] |= uint64_t(1) << (field.input_id % 64);
            }
        }
    }
    const int controller_profile = recompinput::profiles::get_sp_controller_profile_index();
    if (controller_profile >= 0) {
        for (size_t i = 0; i < recompinput::num_bindings_per_input; i++) {
            const auto field = recompinput::profiles::get_input_binding(
                controller_profile, recompinput::GameInput::TOGGLE_MENU, i);
            if (field.input_type == recompinput::InputType::ControllerDigital &&
                field.input_id != SDL_CONTROLLER_BUTTON_BACK &&
                field.input_id >= 0 && field.input_id < 32) {
                controller |= uint32_t(1) << field.input_id;
            }
        }
    }
    for (size_t i = 0; i < kScancodeWords; i++)
        g_custom_keyboard_toggle_scancodes[i] = keyboard[i];
    g_custom_controller_toggle_buttons = controller;
}

static void developer_input_tick() {
    const Uint8* ks = SDL_GetKeyboardState(nullptr);
    if (ks == nullptr) return;

    // Developer warp menu (src/aero_warp.c): F1..F6 warp straight to that track.
    static Uint8 warp_prev[6] = {};
    for (int i = 0; i < 6; i++) {
        const Uint8 down = ks[SDL_SCANCODE_F1 + i];
        if (down && !warp_prev[i]) aero_warp_request(i, -1);
        warp_prev[i] = down;
    }

    // Developer save-state: F7 saves and F8 restores at the next game frame.
    static Uint8 f7_prev = 0, f8_prev = 0;
    const Uint8 f7 = ks[SDL_SCANCODE_F7], f8 = ks[SDL_SCANCODE_F8];
    if (f7 && !f7_prev) aero_savestate_request_save();
    if (f8 && !f8_prev) aero_savestate_request_load();
    f7_prev = f7;
    f8_prev = f8;
}

static void close_controller_handle_locked(SDL_GameController* controller) {
    if (controller == nullptr) return;
    if (controller == g_pad) {
        aero::haptics::stop();
        g_pad = nullptr;
    }
    if (SDL_Joystick* joystick = SDL_GameControllerGetJoystick(controller))
        recompinput::remove_controller_state(SDL_JoystickInstanceID(joystick));
    SDL_GameControllerClose(controller);
}

static void release_removed_controllers() {
    std::lock_guard lock(g_removed_controller_mutex);
    for (SDL_GameController* controller : g_removed_controllers)
        close_controller_handle_locked(controller);
    g_removed_controllers.clear();
}

static void release_all_controller_handles() {
    std::lock_guard lock(g_removed_controller_mutex);
    for (SDL_GameController* controller : g_removed_controllers)
        close_controller_handle_locked(controller);
    g_removed_controllers.clear();

    std::vector<SDL_GameController*> controllers;
    recompinput::collect_all_controller_states(controllers);
    for (SDL_GameController* controller : controllers)
        close_controller_handle_locked(controller);
}

static void close_detached_rumble_controller() {
    std::lock_guard lock(g_removed_controller_mutex);
    std::vector<SDL_GameController*> detached;
    recompinput::collect_detached_controller_states(detached);
    for (SDL_GameController* controller : detached) {
        g_removed_controllers.erase(
            std::remove(g_removed_controllers.begin(), g_removed_controllers.end(), controller),
            g_removed_controllers.end());
        close_controller_handle_locked(controller);
    }
    if (g_pad != nullptr && !SDL_GameControllerGetAttached(g_pad)) {
        SDL_GameController* controller = g_pad;
        g_removed_controllers.erase(
            std::remove(g_removed_controllers.begin(), g_removed_controllers.end(), controller),
            g_removed_controllers.end());
        close_controller_handle_locked(controller);
    }
}

static void refresh_rumble_controller() {
    close_detached_rumble_controller();
    if (g_pad != nullptr && SDL_GameControllerGetAttached(g_pad)) return;
    g_pad = nullptr;
    for (int i = 0; i < SDL_NumJoysticks(); i++) {
        if (!SDL_IsGameController(i)) continue;
        const SDL_JoystickID id = SDL_JoystickGetDeviceInstanceID(i);
        SDL_GameController* controller = SDL_GameControllerFromInstanceID(id);
        if (controller != nullptr && SDL_GameControllerGetAttached(controller)) {
            g_pad = controller;
            return;
        }
    }
}

static void input_poll_stub() {}
static bool input_get_input(int controller_num, uint16_t* buttons, float* x, float* y) {
    if (controller_num != 0) return false;
    if (aero::menu::captures_input()) {
        if (buttons) *buttons = 0;
        if (x) *x = 0;
        if (y) *y = 0;
        return true;
    }
    const uint32_t snapshot = g_input_snapshot.load(std::memory_order_relaxed);
    const int vi = g_vis.load(std::memory_order_relaxed);
    const uint64_t after = g_after_input_packed.load(std::memory_order_relaxed);
    const int after_vi = (int32_t)(after & 0xFFFFFFFFu);
    const bool use_after = after_vi >= 0 && vi >= after_vi;
    const uint16_t held_buttons = use_after ? (uint16_t)(after >> 32) : g_held_buttons;
    const int8_t held_sx = use_after ? (int8_t)(after >> 48) : g_held_sx;
    const int8_t held_sy = use_after ? (int8_t)(after >> 56) : g_held_sy;
    uint16_t b = aero_input_snapshot_buttons(snapshot) | held_buttons;
    if (aero_input_pulse_active(vi, g_pulse_period, g_pulse_duty, g_pulse_start,
                                g_pulse_count))
        b |= g_pulse_buttons;
    int8_t sx = aero_input_snapshot_stick_x(snapshot);
    int8_t sy = aero_input_snapshot_stick_y(snapshot);
    if (sx == 0) sx = held_sx;
    if (sy == 0) sy = held_sy;
    if (buttons) *buttons = b;
    if (x) *x = aero_n64_stick_to_normalized(sx);
    if (y) *y = aero_n64_stick_to_normalized(sy);
    return true;
}
static ultramodern::input::connected_device_info_t input_device_info(int controller_num) {
    using namespace ultramodern::input;
    if (controller_num == 0) return { Device::Controller, Pak::RumblePak };
    return { Device::None, Pak::None };
}

int main(int argc, char** argv) {
#if defined(__ANDROID__)
    if (!aero::android::initialize()) return 2;
#endif
    // Deterministic lighting self-test: no ROM, no runtime -- exercises the swrender
    // light-decode + Lambert path on a synthetic display list and exits.
    if (std::getenv("AERO_LIGHTING_SELFTEST")) {
        return headless::run_lighting_selftest();
    }
    const char* rom_path = (argc > 1) ? argv[1] : "AeroGauge (USA).z64";
    std::fprintf(stderr, "[probe] ROM: %s\n", rom_path);

    register_overlays();
    // After register_overlays so the native-ptr -> vram map is already wired.
    aero::crash::install();

    // Smoke-test the handler: AERO_CRASH_TEST=<reason> schedules a 2 s
    // sleep then a deliberate crash so the dump format can be verified in
    // CI / field testing without waiting for a real bug.
    if (const char* ct = std::getenv("AERO_CRASH_TEST")) {
        std::fprintf(stderr, "[probe] AERO_CRASH_TEST=%s; injecting deliberate crash in 2s\n", ct);
        std::thread([](const char* reason){
            std::this_thread::sleep_for(std::chrono::seconds(2));
            aero::crash::record_recent(0x80001CD0u, 0x800024F8u);  // func_800028D0 entry, $ra into menu driver
            aero::crash::record_recent(0x80000450u, 0);            // BootMain entry
            aero::crash::crash_dump_and_die(reason);
        }, ct).detach();
    }

    // Load + apply graphics.json BEFORE recomp::start: ultramodern latches the config
    // and the RT64 context constructor reads it via get_graphics_config(). This is the
    // whole user-facing options mechanism (edit the file; F11 toggles fullscreen live).
    aero::config::load_and_apply_graphics();

    // librecomp's config path is where game SAVES (EEPROM/SRAM/pak) and mod config
    // live -- point it at the same persistent per-user directory as graphics.json.
    // (It was a throwaway temp dir during the headless-probe era, which silently
    // discarded saves on temp cleanup.)
    std::filesystem::path config_dir = aero::config::app_config_dir();
    std::filesystem::create_directories(config_dir);
    recomp::register_config_path(config_dir);
    auto pak_path = config_dir / "saves" / "aerogauge.us.mpk";
    if (const char* path = std::getenv("AERO_PAK_PATH"); path && *path)
        pak_path = std::filesystem::path(std::u8string(reinterpret_cast<const char8_t*>(path)));
    if (!pak_path.parent_path().empty()) std::filesystem::create_directories(pak_path.parent_path());
    const char* pak_enabled = std::getenv("AERO_CONTROLLER_PAK");
    aero::pak::configure(pak_path, !pak_enabled || std::strcmp(pak_enabled, "0") != 0);
    const char* rumble = std::getenv("AERO_RUMBLE");
    const char* turbo_rumble = std::getenv("AERO_RUMBLE_TURBO");
    aero::haptics::configure(!rumble || std::strcmp(rumble, "0") != 0,
                           !turbo_rumble || std::strcmp(turbo_rumble, "0") != 0);

    recomp::GameEntry game{};
    game.rom_hash          = 0x89ea0690f3e22201ULL; // XXH3_64(big-endian .z64, 8 MiB)
    game.internal_name     = "AEROGAUGE           "; // ROM header name @0x20 (20 bytes)
    game.display_name      = "AeroGauge";
    game.game_id           = u8"aerogauge.us";
    game.is_enabled        = true;
    // 4Kbit EEPROM (512 B): the ROM's save loader (0x80061D00) probes with osEepromProbe and
    // the routed librecomp eep.cpp natives gate on this via recomp::eeprom_allowed(). The
    // probe status bits in __osEepStatus map 0x8000 -> type 1 (4K), which is what this
    // cartridge shipped with.
    game.save_type         = recomp::SaveType::Eep4k;
    game.entrypoint_address = (gpr)(int32_t)0x80000400u;
    game.entrypoint        = recomp_entrypoint;
    game.on_init_callback  = on_init_cb;
    game.thread_create_callback = thread_create_cb;
    recomp::register_game(game);

    std::u8string game_id = u8"aerogauge.us";
    recomp::RomValidationError verr = recomp::select_rom(rom_path, game_id);
    if (verr != recomp::RomValidationError::Good) {
        std::fprintf(stderr, "[probe] select_rom FAILED (RomValidationError=%d)\n", (int)verr);
        return 1;
    }
    std::fprintf(stderr, "[probe] ROM validated; rom_hash matches\n");

    // recomp::start() blocks the calling thread until ultramodern::quit(), so
    // kick the game off from a side thread once the runtime has set up.
    std::thread starter([game_id]() {
        std::this_thread::sleep_for(std::chrono::milliseconds(150));
        std::fprintf(stderr, "[probe] calling start_game\n");
        std::u8string gid = game_id;
        recomp::start_game(gid, "");
    });
    starter.detach();

    // Watchdog: guarantee the probe terminates and reports, even on a stall.
    const int wd_sec = watchdog_seconds();
    std::thread watchdog([wd_sec]() {
        std::this_thread::sleep_for(std::chrono::seconds(wd_sec));
        std::fprintf(stderr, "[probe] WATCHDOG %ds: threads=%d vis=%d first_vi=%d\n",
                     wd_sec, g_threads.load(), g_vis.load(), (int)g_first_vi.load());
        // Exit deterministically (same as the VI-cap path) rather than ultramodern::quit(),
        // whose teardown munmaps RDRAM out from under the live game threads (SIGSEGV race).
        boot_summary_and_exit();
    });
    watchdog.detach();

    recomp::Configuration cfg{};
    cfg.project_version = recomp::Version{1, 0, 0, std::string{}};
    cfg.rsp_callbacks.get_rsp_microcode = get_rsp_microcode_stub;
    cfg.renderer_callbacks.create_render_context = headless::create_render_context;
    cfg.gfx_callbacks.create_window = create_window_stub; // avoids start()'s no-window assert
    cfg.gfx_callbacks.update_gfx = update_gfx_stub;       // SDL event pump when RT64 is active
    cfg.events_callbacks.vi_callback = vi_cb;
    cfg.error_handling_callbacks.message_box = message_box_stub;
    // window_handle left default-empty -> create_window_stub() is used.

    // Keyboard and the first SDL gamepad share controller 0. The runtime's
    // RumblePak capability supplies accessory-present status and motor callbacks;
    // the separate native block device lets the ROM use memory and rumble together.
    // AERO_MODERN_INPUT still overrides the held-button mask for input testing (e.g. =1000 holds
    // START); default (unset) = controller 0 connected, no buttons held.
    if (const char* in = std::getenv("AERO_MODERN_INPUT")) {
        // Format: BTNHEX[:SX[:SY]]. OS_CONT bits: START=0x1000, A=0x8000, B=0x4000; SX/SY are
        // signed decimal stick values. e.g. AERO_MODERN_INPUT=1000 holds START;
        // AERO_MODERN_INPUT=0:53:0 holds the stick at x=+53 with no buttons.
        char* end = nullptr;
        g_held_buttons = (uint16_t)std::strtoul(in, &end, 16);
        if (end != nullptr && *end == ':') {
            g_held_sx = (int8_t)std::strtol(end + 1, &end, 10);
            if (end != nullptr && *end == ':') {
                g_held_sy = (int8_t)std::strtol(end + 1, nullptr, 10);
            }
        }
    }
    if (const char* in = std::getenv("AERO_MODERN_INPUT_AFTER")) {
        // Format: STARTVI:BTNHEX:SX:SY. At STARTVI, atomically replace all three
        // AERO_MODERN_INPUT fields. Intended for deterministic headless test scenarios.
        int start_vi = -1, sx = 0, sy = 0;
        unsigned buttons = 0;
        char trailing = '\0';
        if (std::sscanf(in, "%d:%x:%d:%d%c", &start_vi, &buttons, &sx, &sy,
                        &trailing) == 4 && start_vi >= 0 && buttons <= 0xFFFFu &&
            sx >= -127 && sx <= 127 && sy >= -127 && sy <= 127) {
            const uint64_t packed = (uint32_t)start_vi |
                                    ((uint64_t)(uint16_t)buttons << 32) |
                                    ((uint64_t)(uint8_t)sx << 48) |
                                    ((uint64_t)(uint8_t)sy << 56);
            g_after_input_packed.store(packed, std::memory_order_release);
            std::fprintf(stderr, "[probe] input after: vi=%d buttons=%04x stick=%d,%d\n",
                         start_vi, buttons, sx, sy);
        } else {
            std::fprintf(stderr, "[probe] ignoring malformed AERO_MODERN_INPUT_AFTER=%s\n", in);
        }
    }
    if (const char* pu = std::getenv("AERO_INPUT_PULSE")) {
        // BTNHEX:PERIOD:DUTY[:STARTVI[:COUNT]], VI units. e.g. 1000:150:4:300 taps START for 4 VIs
        // every 150 VIs starting at VI 300 -- enough edges to walk the whole menu chain headless.
        // COUNT stops after N taps (0/absent = unlimited) so a walk can PARK on a target screen.
        char* end = nullptr;
        g_pulse_buttons = (uint16_t)std::strtoul(pu, &end, 16);
        if (end && *end == ':') g_pulse_period = (int)std::strtol(end + 1, &end, 10);
        if (end && *end == ':') g_pulse_duty   = (int)std::strtol(end + 1, &end, 10);
        if (end && *end == ':') g_pulse_start  = (int)std::strtol(end + 1, &end, 10);
        if (end && *end == ':') g_pulse_count  = (int)std::strtol(end + 1, nullptr, 10);
        std::fprintf(stderr, "[probe] input pulse: btn=%04x period=%d duty=%d start=%d count=%d\n",
                     g_pulse_buttons, g_pulse_period, g_pulse_duty, g_pulse_start, g_pulse_count);
    }
    cfg.input_callbacks.poll_input = input_poll_stub;
    cfg.input_callbacks.get_input = input_get_input;
    cfg.input_callbacks.set_rumble = [](int channel, bool on) {
        if (channel == 0) aero_pak_set_rumble(on);
    };
    cfg.input_callbacks.get_connected_device_info = input_device_info;
    std::fprintf(stderr, "[probe] input: controller0 connected (default), buttons=%04x\n", g_held_buttons);

    // Audio path: populate the host callbacks before starting the runtime.
    // The runtime sets the AI frequency during startup; generated audio calls
    // then submit buffers through the callback table. See
    // docs/reference/audio.md for the ownership and generated-code boundary.
    aero::audio::init(48000);
    aero::audio::get_callbacks(&cfg.audio_callbacks);
    std::fprintf(stderr, "[probe] audio: callbacks wired (queue_samples/get_frames_remaining/set_frequency)\n");

    std::fprintf(stderr, "[probe] calling recomp::start\n");
    recomp::start(cfg);
    // Reached only via the watchdog quit path (a boot stall before the VI cap): the VI-cap
    // path exits from vi_cb via boot_summary_and_exit() and never returns here.
    boot_summary_and_exit();
}
