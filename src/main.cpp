// Highest scene id (0x8013FF80, the scene manager's current-scene word) observed during
// the run. Lets a boot smoke run assert the boot cascade reaches the attract/race scenes
// (logo 0 -> attract 2 / title 3 -> menu 4 -> race 5) rather than just "didn't crash".
// See state_probe().
static std::atomic<int>  g_max_state{0};
static std::atomic<int>  g_swaps{0};

// AERO_CRASH_TEST: when set, the test thread's 2 s sleep must outlast
// boot_summary_and_exit() so its deliberate crash fires. Disable the VI cap.
static int quit_after_vis() {
    if (const char* e = std::getenv("AERO_MODERN_MAX_VIS")) {
        int v = std::atoi(e);
        if (v > 0) return v;
    }
    if (std::getenv("AERO_CRASH_TEST")) return std::numeric_limits<int>::max();
    return aero_rt64::enabled() ? std::numeric_limits<int>::max() : 120;
}
static const int kQuitAfterVis = quit_after_vis();

// Stall watchdog timeout. MUST exceed the wall-time the VI budget needs, or a raised
// AERO_MODERN_MAX_VIS is silently truncated by the watchdog before reaching the cap.
// Derive it from the cap (headless runs well above 10 VI/s, so cap/10 is generous) with
// a 30 s floor for the default boot. Uncapped play mode gets no watchdog (INT_MAX/10
// seconds is effectively never, and killing a live game window from a stall heuristic
// would be wrong anyway).
static int watchdog_seconds() {
    return std::max(30, kQuitAfterVis / 10 + 5);
}

